#!/usr/bin/env node
// Regenerates content.js (the embedded docs corpus) from the markdown sources.
// Zero dependencies. Run from the docs/ directory:  node build.js
// The site (index.html) works from file:// because the content is embedded —
// no fetch(), no server, no CORS.
//
// Bilingual: each doc embeds the English source plus, when present, the
// Spanish translation from docs/es/<id>.md. Missing translations fall back
// to English at runtime (and are reported here).

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

/** Nav structure: groups → docs. `file` is relative to the repo root. */
const NAV = [
  {
    group: 'Start',
    group_es: 'Inicio',
    items: [
      { id: 'overview', title: 'Overview', title_es: 'Visión general', file: 'README.md' },
      { id: 'install', title: 'Installation', title_es: 'Instalación', file: 'docs/install.md' },
    ],
  },
  {
    group: 'Guides',
    group_es: 'Guías',
    items: [
      { id: 'authoring-models', title: 'Authoring models', title_es: 'Escribir modelos', file: 'docs/authoring-models.md' },
      { id: 'migrations', title: 'Migrations', title_es: 'Migraciones', file: 'docs/migrations.md' },
      { id: 'team-database-workflow', title: 'Team workflow', title_es: 'Flujo de equipo', file: 'docs/team-database-workflow.md' },
      { id: 'ci-github-actions', title: 'CI · GitHub Actions', title_es: 'CI · GitHub Actions', file: 'docs/ci-github-actions.md' },
    ],
  },
  {
    group: 'Reference',
    group_es: 'Referencia',
    items: [
      { id: 'cli', title: 'CLI reference', title_es: 'Referencia del CLI', file: 'docs/cli.md' },
      { id: 'molde-language-spec', title: 'Language spec', title_es: 'Especificación del lenguaje', file: 'docs/molde-language-spec.md' },
      { id: 'model-ir', title: 'Model IR', title_es: 'IR del modelo', file: 'docs/model-ir.md' },
    ],
  },
  {
    group: 'Ecosystem',
    group_es: 'Ecosistema',
    items: [
      { id: 'vscode', title: 'VS Code extension', title_es: 'Extensión de VS Code', file: 'editors/vscode/README.md' },
      { id: 'competitive-research', title: 'Design notes', title_es: 'Notas de diseño', file: 'docs/competitive-research.md' },
    ],
  },
];

const docs = [];
const missingEs = [];
for (const group of NAV) {
  for (const item of group.items) {
    const markdown = fs.readFileSync(path.join(ROOT, item.file), 'utf8');
    const esPath = path.join(__dirname, 'es', `${item.id}.md`);
    let markdown_es = null;
    if (fs.existsSync(esPath)) {
      markdown_es = fs.readFileSync(esPath, 'utf8');
    } else {
      missingEs.push(item.id);
    }
    docs.push({
      id: item.id,
      group: group.group,
      group_es: group.group_es,
      title: item.title,
      title_es: item.title_es,
      file: item.file,
      markdown,
      markdown_es,
    });
  }
}

const header =
  '// GENERATED by build.js — do not edit by hand. Re-run `node build.js` after\n' +
  '// changing any markdown source (English or docs/es/). Embedded for file://.\n';
const body = 'window.DOCS = ' + JSON.stringify(docs, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, 'content.js'), header + body);
console.log(`content.js: ${docs.length} documents, ${((header.length + body.length) / 1024).toFixed(0)} KB`);
if (missingEs.length) console.log(`sin traducción (fallback a inglés): ${missingEs.join(', ')}`);
