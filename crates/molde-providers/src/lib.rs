//! # molde-providers
//!
//! Engine-specific SQL generation. Defines the [`SqlGenerator`] trait and its
//! implementations. In Phase 0 there are two: SQLite (fast tests) and PostgreSQL.
//! SQL Server and MySQL arrive in a later phase following the same trait.

pub mod generator;
pub mod mysql;
pub mod postgres;
pub mod sqlite;
pub mod sqlserver;

pub use generator::{ProviderError, SqlGenerator};
pub use mysql::MySqlGenerator;
pub use postgres::PostgresGenerator;
pub use sqlite::SqliteGenerator;
pub use sqlserver::SqlServerGenerator;

/// Supported engines.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Provider {
    Sqlite,
    Postgres,
    MySql,
    /// SQL Server: apply and scaffold via tiberius (TDS driver).
    SqlServer,
}

impl Provider {
    /// Resolves a provider from a string (`--provider postgres`).
    pub fn parse(s: &str) -> Option<Self> {
        match s.to_ascii_lowercase().as_str() {
            "sqlite" => Some(Self::Sqlite),
            "postgres" | "postgresql" | "npgsql" => Some(Self::Postgres),
            "mysql" | "mariadb" => Some(Self::MySql),
            "sqlserver" | "mssql" => Some(Self::SqlServer),
            _ => None,
        }
    }

    /// Infers the provider from the scheme of an sqlx connection string.
    pub fn from_url(url: &str) -> Option<Self> {
        let lower = url.trim().to_ascii_lowercase();
        if lower.starts_with("postgres://") || lower.starts_with("postgresql://") {
            Some(Self::Postgres)
        } else if lower.starts_with("sqlite:") {
            Some(Self::Sqlite)
        } else if lower.starts_with("mysql://") || lower.starts_with("mariadb://") {
            Some(Self::MySql)
        } else if lower.starts_with("sqlserver://") || lower.starts_with("mssql://") {
            Some(Self::SqlServer)
        } else {
            None
        }
    }

    /// Returns the corresponding generator as a trait object.
    pub fn generator(self) -> Box<dyn SqlGenerator> {
        match self {
            Self::Sqlite => Box::new(SqliteGenerator::new()),
            Self::Postgres => Box::new(PostgresGenerator::new()),
            Self::MySql => Box::new(MySqlGenerator::new()),
            Self::SqlServer => Box::new(SqlServerGenerator::new()),
        }
    }
}

