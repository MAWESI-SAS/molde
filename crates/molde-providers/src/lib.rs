    #[test]
    fn sqlite_rebuild_table_sequence() {
        use molde_core::model::PrimaryKey;
        let mut t = customer();
        t.name = "Order".into();
        t.primary_key = Some(PrimaryKey {
            name: "PK_Order".into(),
            columns: vec!["Id".into()],
        });
        let op = Operation::RebuildTable {
            table: t,
            copy_columns: vec!["Id".into(), "Name".into()],
        };
        let sql = SqliteGenerator::new().emit(&op).unwrap();
        let joined = sql.join("\n");
        assert!(
            joined.contains("CREATE TABLE \"Order_molde_new\""),
            "got: {joined}"
        );
        assert!(joined.contains("INSERT INTO \"Order_molde_new\" (\"Id\", \"Name\") SELECT \"Id\", \"Name\" FROM \"Order\";"));
        assert!(joined.contains("DROP TABLE \"Order\";"));
        assert!(joined.contains("ALTER TABLE \"Order_molde_new\" RENAME TO \"Order\";"));

        // Capable engines: RebuildTable is a no-op (they use granular ALTER).
        assert!(PostgresGenerator::new().emit(&op).unwrap().is_empty());
        assert!(MySqlGenerator::new().emit(&op).unwrap().is_empty());
    }

